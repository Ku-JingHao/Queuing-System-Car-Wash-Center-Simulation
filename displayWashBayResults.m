function displayWashBayResults(title, bayData)
    printf('\n%s:\n', title);
    disp('+-------------------------------------------------------------------------------------------------------------------------------------------+');
    disp('|  n |  RN for service time  |  Service time  |  Time service begins  |  Time service ends  |  Waiting time  |  Time spends in the system   |');
    disp('+-------------------------------------------------------------------------------------------------------------------------------------------+');

    for i = 1:size(bayData, 1)
        fprintf('| %2d |%12d           |%8d        |%13d          |%11d          | %8d       | %14d               |\n', bayData(i,:));
    end
    disp('+-------------------------------------------------------------------------------------------------------------------------------------------+');
end